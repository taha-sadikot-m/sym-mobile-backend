def all_countries() -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    for region, members in MEMBERS.items():
        rows.extend(
            {"code": code, "name": name, "region": region, "is_un_member": True} for code, name in members
        )
    rows.extend(
        {"code": code, "name": name, "region": region, "is_un_member": False}
        for code, name, region in OBSERVERS
    )
    for row in rows:
        code = str(row["code"])
        row["groupings"] = sorted(group for group, codes in GROUPINGS.items() if code in codes)
        row["summary"] = SUMMARIES.get(code, "")
    return rows
